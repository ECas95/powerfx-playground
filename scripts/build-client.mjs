import {readFile,writeFile} from 'node:fs/promises';

// Ship a single classic browser script: GitHub Pages must not need to resolve
// a second ES module before the explorer can render its scenario library.
const root=new URL('../',import.meta.url);
const scenarios=await readFile(new URL('public/scenarios.js',root),'utf8');
const app=await readFile(new URL('public/app.js',root),'utf8');
const catalog=await readFile(new URL('public/function-catalog.js',root),'utf8');
const helpers=await readFile(new URL('public/client-tools.js',root),'utf8');
const scenarioMatch='export const scenarios = [';
const importMatch="import {scenarios as examples} from './scenarios.js';";
const catalogImport="import {functionCatalog} from './function-catalog.js';";
const helpersImport="import {completionContext,functionMatches,csvSerialize,jsonTreeLabel,validateSuite} from './client-tools.js';";
if(!scenarios.includes(scenarioMatch)||!app.startsWith([importMatch,catalogImport,helpersImport].join('\n'))){
  throw new Error('Client sources changed: update the bundler rather than shipping an empty scenario library.');
}
const source=[
  '// Generated by scripts/build-client.mjs — do not edit directly.\n',
  scenarios.replace(scenarioMatch,'const scenarios = ['),
  '\nconst examples = scenarios;\n',
  catalog.replace('export const functionCatalog=','const functionCatalog='),
  helpers.replaceAll('export function ','function '),
  app.slice([importMatch,catalogImport,helpersImport].join('\n').length).trimStart(),
  '\n'
].join('');
new Function(source); // Ensure the delivered classic script parses in the JS engine.
const target=new URL('public/workbench.js',root);
if(process.argv.includes('--check')){
  const existing=await readFile(target,'utf8');
  if(existing!==source)throw new Error('public/workbench.js is stale — run npm run build:client.');
  console.log('Browser bundle is current');
}else{
  await writeFile(target,source,'utf8');
  console.log('Single-file browser workbench ready:',Buffer.byteLength(source),'bytes');
}
